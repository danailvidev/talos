/** Converts known standard shortcodes; custom workspace emoji remain readable. */
export function replaceSlackEmojiShortcodes(text: string): string {
  return text.replace(/:([+\-\w]+):/g, (token, name: string) => {
    return STANDARD_SLACK_EMOJI[name] ?? token;
  });
}
